/** Подпись кнопки отправки и подсказка рядом с ней. */
export function submitLabel(sending: boolean): string {
  return sending ? 'Отправляем…' : 'Отправить заявку'
}

export function submitHint(sending: boolean, consent: boolean): string {
  if (sending) return 'Отправляем заявку команде WEXUS…'
  return consent
    ? 'Заявка уйдёт письмом команде WEXUS.'
    : 'Кнопка станет активной, когда ты отметишь согласие.'
}

