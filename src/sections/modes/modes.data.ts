/**
 * Данные экрана «Два режима»: вкладки переключателя с текстами панелей
 * и три шага подключения.
 */

/** Режим работы устройства. Первый — основной (автономный). */
export type Mode = 'solo' | 'local'

export interface ModeInfo {
  id: Mode
  /** подпись на вкладке переключателя */
  label: string
  /** текст панели под переключателем */
  text: string
}

export const MODES: readonly ModeInfo[] = [
  {
    id: 'solo',
    label: 'Без интернета',
    text: 'Основной режим. Устройство работает от собственного аккумулятора и поднимает свою сеть — файлы открываются там, где сети нет вообще: в поезде, на съёмке, в горах.',
  },
  {
    id: 'local',
    label: 'В домашней сети',
    text: 'Дополнительный режим. Дома или в офисе устройство подключается к обычному Wi-Fi: хранилище видят все устройства в этой сети, а при наличии интернета доступ появляется в любой точке мира.',
  },
]

/** Режим, выбранный при загрузке страницы */
export const DEFAULT_MODE: Mode = 'solo'

/** id вкладки и панели: на них ссылаются aria-controls / aria-labelledby */
export const tabId = (mode: Mode) => `tab-${mode}`
export const panelId = (mode: Mode) => `panel-${mode}`

